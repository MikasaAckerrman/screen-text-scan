import android.graphics.Rect;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Тест порядка чтения. Rect подменяется настоящей реализацией из tests/stub —
 * в android.jar все методы бросают "Stub!".
 *
 * ЗАЧЕМ. Порядок — то, что пользователь видит первым, и ошибка в нём тихая:
 * текст прочитан весь, но перемешан. На устройстве это выглядит как «читает
 * как попало», а причина может быть в пяти пикселях разницы по вертикали.
 */
public class ReadingOrderTest {

    static int ok = 0, fail = 0;

    static void check(String what, boolean cond) {
        if (cond) {
            ok++;
            System.out.println("ОК    " + what);
        } else {
            fail++;
            System.out.println("ПРОВАЛ " + what);
        }
    }

    static void eq(String what, List<String> got, String... want) {
        boolean good = got.equals(Arrays.asList(want));
        if (!good) {
            System.out.println("       ожидали " + Arrays.asList(want));
            System.out.println("       получили " + got);
        }
        check(what, good);
    }

    static ReadingOrder.Item it(String text, int l, int t, int r, int b) {
        return new ReadingOrder.Item(text, new Rect(l, t, r, b), false);
    }

    static ReadingOrder.Item virt(String text, int l, int t, int r, int b) {
        return new ReadingOrder.Item(text, new Rect(l, t, r, b), true);
    }

    public static void main(String[] a) {

        /* ---------- обычный столбец ---------- */
        eq("простой столбец сверху вниз",
                ReadingOrder.sort(Arrays.asList(
                        it("третья", 0, 300, 500, 340),
                        it("первая", 0, 100, 500, 140),
                        it("вторая", 0, 200, 500, 240))),
                "первая", "вторая", "третья");

        /* ---------- порядок дерева не совпадает с экранным ----------
         * Главный случай: обход дерева выдал заголовок последним. */
        eq("заголовок встал на место",
                ReadingOrder.sort(Arrays.asList(
                        it("тело статьи", 0, 400, 900, 440),
                        it("подзаголовок", 0, 300, 900, 340),
                        it("ЗАГОЛОВОК", 0, 100, 900, 180))),
                "ЗАГОЛОВОК", "подзаголовок", "тело статьи");

        /* ---------- строка из нескольких надписей ----------
         * Ровно то, из-за чего простая сортировка по y не работает: три
         * надписи на одной высоте, но с разным y из-за разного кегля. */
        eq("надписи одной строки идут слева направо",
                ReadingOrder.sort(Arrays.asList(
                        it("Следить", 700, 1209, 900, 1249),
                        it("Язык", 100, 1204, 250, 1254),
                        it("Скачать PDF", 300, 1206, 600, 1246))),
                "Язык", "Скачать PDF", "Следить");

        /*
         * И самое коварное: надпись из СЛЕДУЮЩЕЙ строки с промежуточным y.
         * Простая сортировка по y вклинила бы её в середину предыдущей
         * строки. Группировка по перекрытию — нет.
         */
        eq("надпись следующей строки не вклинивается",
                ReadingOrder.sort(Arrays.asList(
                        it("лево", 100, 1000, 300, 1040),
                        it("право", 700, 1005, 900, 1045),
                        it("следующая строка", 100, 1060, 900, 1100))),
                "лево", "право", "следующая строка");

        /* ---------- таблица ----------
         * Два столбца: без группировки в полосы получилось бы
         * «метка метка метка значение значение значение». */
        eq("таблица читается по строкам, а не по столбцам",
                ReadingOrder.sort(Arrays.asList(
                        it("Состояние", 100, 200, 400, 240),
                        it("Лицензия", 100, 300, 400, 340),
                        it("Версия", 100, 100, 400, 140),
                        it("4.6", 600, 100, 900, 140),
                        it("заменён", 600, 200, 900, 240),
                        it("EULA", 600, 300, 900, 340))),
                "Версия", "4.6", "Состояние", "заменён", "Лицензия", "EULA");

        /* ---------- крупный заголовок ----------
         * Заголовок высотой 100 перекрывает три мелкие строки под собой.
         * Без проверки соотношения высот они слились бы с ним в одну полосу
         * и вышли бы в одну строку. */
        eq("крупный заголовок не вбирает мелкий текст",
                ReadingOrder.sort(Arrays.asList(
                        it("БОЛЬШОЙ ЗАГОЛОВОК", 0, 100, 900, 200),
                        it("мелкая одна", 0, 210, 900, 235),
                        it("мелкая два", 0, 240, 900, 265))),
                "БОЛЬШОЙ ЗАГОЛОВОК", "мелкая одна", "мелкая два");

        /* ---------- виртуальные координаты ----------
         * WebView считает от начала документа: y бывает отрицательным.
         * Смешивать с экранными нельзя — надпись с y=-4000 встала бы
         * впереди всего экрана. */
        eq("документные координаты идут после экранных",
                ReadingOrder.sort(Arrays.asList(
                        virt("тело страницы", 0, -4000, 900, -3960),
                        it("адресная строка", 0, 100, 900, 140),
                        virt("заголовок страницы", 0, -4100, 900, -4050))),
                "адресная строка", "заголовок страницы", "тело страницы");

        check("пустой список не ломает", ReadingOrder.sort(new ArrayList<>()).isEmpty());
        check("пустые строки выброшены",
                ReadingOrder.sort(Arrays.asList(
                        it("", 0, 0, 10, 10),
                        it("текст", 0, 20, 10, 30))).size() == 1);

        /* ---------- склейка разрезанного предложения ----------
         * Одно предложение в вёрстке часто разбито на элементы: ссылка
         * внутри текста — отдельная надпись. */
        eq("разрезанное предложение склеивается",
                ReadingOrder.joinRow(
                        Arrays.asList("Использовался при создании", "компьютерных игр", ","),
                        Arrays.asList(new Rect(100, 100, 500, 140),
                                new Rect(510, 100, 700, 140),
                                new Rect(700, 100, 715, 140))),
                "Использовался при создании компьютерных игр,");

        eq("законченное предложение не склеивается со следующим",
                ReadingOrder.joinRow(
                        Arrays.asList("Первое предложение.", "Второе предложение"),
                        Arrays.asList(new Rect(100, 100, 400, 140),
                                new Rect(410, 100, 700, 140))),
                "Первое предложение.", "Второе предложение");

        eq("далеко стоящие надписи не склеиваются",
                ReadingOrder.joinRow(
                        Arrays.asList("Метка", "Значение"),
                        Arrays.asList(new Rect(100, 100, 300, 140),
                                new Rect(800, 100, 1000, 140))),
                "Метка", "Значение");

        System.out.println();
        System.out.println("итог: " + ok + " ок, " + fail + " провал");
        if (fail > 0) System.exit(1);
    }
}
